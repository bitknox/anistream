#!/usr/bin/env bash
# Bundles seal.js and @noble/ciphers (pinned in package.json and bun.lock) into the one script the
# TV's QR pages serve inline. Run after changing either, and commit what it writes.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../src/main/resources/tv/anistream/tv/signin/page-crypto.js"
cd "$here"
bun install --frozen-lockfile >/dev/null
mkdir -p "$(dirname "$out")"
{
  echo "/* Generated by android/tv/page-crypto/build.sh from seal.js and @noble/ciphers $(bun pm ls 2>/dev/null | grep -o '@noble/ciphers@[0-9.]*' | cut -d@ -f3) (MIT, (c) Paul Miller). Do not edit. */"
  bun build seal.js --format=iife --minify-whitespace --target=browser
} > "$out"
echo "wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
