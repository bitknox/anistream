//! Turns `assets/mpv/` into a file table the player crate embeds.
//!
//! The table is generated rather than written by hand so that a file added anywhere under the
//! directory ships without anyone remembering to list it: uosc alone is forty files, and the
//! companion script is a directory that grows. The content hash is computed here too, once
//! per build, so the binary never hashes megabytes of fonts at launch to find out whether its
//! cache is current.

use std::{
    env,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use sha2::{Digest, Sha256};

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let root = manifest
        .parent()
        .and_then(Path::parent)
        .expect("the crate lives at crates/anistream-player")
        .join("assets")
        .join("mpv");

    println!("cargo::rerun-if-changed=build.rs");

    let mut files = Vec::new();
    walk(&root, &root, &mut files);
    // Sorted so that the hash, and the generated source, depend only on the tree's contents and
    // not on the order the filesystem lists them in.
    files.sort();

    let mut hasher = Sha256::new();
    let mut table = String::new();
    for (relative, path) in &files {
        let bytes =
            fs::read(path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
        hasher.update(relative.as_bytes());
        hasher.update([0]);
        hasher.update((bytes.len() as u64).to_le_bytes());
        hasher.update(&bytes);
        let absolute = path.to_str().unwrap_or_else(|| panic!("non-UTF-8 path {path:?}"));
        // `{:?}` escapes the backslashes of a Windows path into a valid string literal.
        writeln!(table, "    ({relative:?}, include_bytes!({absolute:?})),").unwrap();
    }
    let digest = hasher.finalize();
    // Sixteen hex digits: a directory name, not a signature. Collisions between two builds of
    // the same program's assets are not a realistic failure.
    let mut hash = String::new();
    for byte in &digest[..8] {
        write!(hash, "{byte:02x}").unwrap();
    }

    let source = format!(
        "// Generated by build.rs from assets/mpv/. Do not edit.\n\
         const HASH: &str = {hash:?};\n\
         const FILES: &[(&str, &[u8])] = &[\n{table}];\n"
    );
    let out =
        PathBuf::from(env::var_os("OUT_DIR").expect("set by cargo")).join("mpv_bundle.rs");
    fs::write(&out, source).unwrap_or_else(|e| panic!("writing {}: {e}", out.display()));
}

/// Collect `(relative path with '/' separators, absolute path)` for every file under `dir`.
///
/// Dot-files are skipped: `.DS_Store` appears the moment someone opens the folder in Finder,
/// and shipping it would also change the hash on that one machine.
fn walk(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    // Cargo scans a directory named here recursively for the newest mtime, and adding or
    // removing a file changes its directory's mtime. Every directory is named anyway, so a new
    // file in a nested one cannot hide behind a scan that only compares files.
    println!("cargo::rerun-if-changed={}", dir.display());
    let entries =
        fs::read_dir(dir).unwrap_or_else(|e| panic!("listing {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("listing {}: {e}", dir.display()));
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_str().unwrap_or_else(|| panic!("non-UTF-8 name {path:?}"));
        if name.starts_with('.') {
            continue;
        }
        let kind = entry.file_type().unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        if kind.is_dir() || (kind.is_symlink() && path.is_dir()) {
            walk(root, &path, files);
        } else {
            let relative = path
                .strip_prefix(root)
                .expect("walked from root")
                .components()
                .map(|c| c.as_os_str().to_str().expect("checked above"))
                .collect::<Vec<_>>()
                .join("/");
            files.push((relative, path));
        }
    }
}
