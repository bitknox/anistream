//! Windows: `Strings/<lang>/Resources.resw`, and the static class `T` with one member per message.
//!
//! `.resw` has no plurals, so a plural message is several keys (`Key_one`, `Key_other`) and `T`
//! picks the form with a table generated from CLDR. `T` lives in the app's core project, which
//! knows nothing of WinUI: the app hands it a resolver over its resource loader, and until it
//! does, or for a key the language lacks, `T` answers with the English compiled into it.

use anyhow::Result;

use crate::catalogue::{Arg, ArgType, Body, Catalogue, Part, Platform};
use crate::plural::Table;
use crate::ship::{Mode, Shipped, select};
use crate::util::{Files, c_escape, one_line, pascal, xml_escape};

const RESW: &str = "desktop/windows/Anistream.Windows/Strings";
/// Windows' pseudo-locale, made from English, outside `Strings/` so only a testing build packs it.
const PSEUDO: &str = "desktop/windows/Anistream.Windows/Strings.Pseudo/qps-ploc/Resources.resw";
const CLASS: &str = "desktop/windows/Anistream.App.Core/Strings.g.cs";
/// Where the engine's `Msg` is rendered: the app's core, which sees both the bindings and `T`.
const MSG: &str = "desktop/windows/Anistream.App.Core/MsgText.g.cs";

pub fn generate(cat: &Catalogue, mode: Mode) -> Result<Files> {
    let langs = select(cat, mode, |only| only.is_none() || only == Some(Platform::Windows))?;
    let mut files = Files::new();
    for lang in &langs {
        files.insert(format!("{RESW}/{}/Resources.resw", lang.tag), resw(lang, |b| b.clone()));
    }
    files.insert(PSEUDO.to_owned(), resw(&langs[0], crate::pseudo::body));
    files.insert(CLASS.to_owned(), class(&langs)?);
    files.insert(MSG.to_owned(), msg_text(cat));
    Ok(files)
}

/// `{name}` placeholders, which `T` fills in. Literal braces are doubled.
fn text(parts: &[Part]) -> String {
    parts
        .iter()
        .map(|p| match p {
            Part::Text(t) => t.replace('{', "{{").replace('}', "}}"),
            Part::Var(v) => format!("{{{v}}}"),
            Part::Term { .. } => unreachable!("terms are inlined before generation"),
        })
        .collect()
}

/// Every key a message is stored under, with its text.
fn keys(name: &str, body: &Body) -> Vec<(String, String)> {
    match body {
        Body::Plain(parts) => vec![(name.to_owned(), text(parts))],
        Body::Plural { variants, .. } => variants
            .iter()
            .map(|v| (format!("{name}_{}", v.category), text(&v.parts)))
            .collect(),
    }
}

