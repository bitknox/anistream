fn resw(lang: &Shipped, map: impl Fn(&Body) -> Body) -> String {
    let mut out = String::from(RESW_HEAD);
    for entry in &lang.entries {
        let m = &entry.source;
        for (key, value) in keys(&pascal(&m.id), &map(&entry.body)) {
            out.push_str(&format!(
                "  <data name=\"{key}\" xml:space=\"preserve\">\n    <value>{}</value>\n",
                xml_escape(&value)
            ));
            if lang.is_source && !m.comment.is_empty() {
                out.push_str(&format!(
                    "    <comment>{}</comment>\n",
                    xml_escape(&one_line(&m.comment))
                ));
            }
            out.push_str("  </data>\n");
        }
    }
    out.push_str("</root>\n");
    out
}

fn signature(args: &[Arg]) -> String {
    args.iter()
        .map(|a| {
            format!(
                "{} {}",
                if a.ty.is_int() { "long" } else { "string" },
                lower_first(&pascal(&a.name))
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// An argument's name as a C# identifier: lower-cased at the front, with a reserved word (`operator`,
/// `event`, `object`) prefixed by `@`.
fn lower_first(s: &str) -> String {
    const RESERVED: &[&str] = &[
        "abstract",
        "as",
        "base",
        "bool",
        "break",
        "byte",
        "case",
        "catch",
        "char",
        "checked",
        "class",
        "const",
        "continue",
        "decimal",
        "default",
        "delegate",
        "do",
        "double",
        "else",
        "enum",
        "event",
        "explicit",
        "extern",
        "false",
        "finally",
        "fixed",
        "float",
        "for",
        "foreach",
        "goto",
        "if",
        "implicit",
        "in",
        "int",
        "interface",
        "internal",
        "is",
        "lock",
        "long",
        "namespace",
        "new",
        "null",
        "object",
        "operator",
        "out",
        "override",
        "params",
        "private",
        "protected",
        "public",
        "readonly",
        "ref",
        "return",
        "sbyte",
        "sealed",
        "short",
        "sizeof",
        "stackalloc",
        "static",
        "string",
        "struct",
        "switch",
        "this",
        "throw",
        "true",
        "try",
        "typeof",
        "uint",
        "ulong",
        "unchecked",
        "unsafe",
        "ushort",
        "using",
        "virtual",
        "void",
        "volatile",
        "while",
    ];
    let mut c = s.chars();
    let lowered: String =
        c.next().map(|f| f.to_lowercase().chain(c).collect()).unwrap_or_default();
    if RESERVED.contains(&lowered.as_str()) { format!("@{lowered}") } else { lowered }
}

fn class(langs: &[Shipped]) -> Result<String> {
    let mut out = String::from(
        "// <auto-generated>\n// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n// </auto-generated>\n#nullable enable\n\nnamespace Anistream.App;\n\n",
    );
    out.push_str("/// <summary>Every string the app shows, by catalogue id: a member per message.</summary>\npublic static partial class T\n{\n");
    out.push_str(
        r#"    /// <summary>Looks a resource key up in the app's resources (its resource loader); null or empty when the key has no text.</summary>
    public static Func<string, string?>? Resolver { get; set; }

    /// <summary>The language the resolver answers in, which picks plural forms. Set with the resolver.</summary>
    public static string Language { get; set; } = "en";

"#,
    );
    for entry in &langs[0].entries {
        let m = &entry.source;
        let name = pascal(&m.id);
        if !m.comment.is_empty() {
            out.push_str(&format!(
                "    /// <summary>{}</summary>\n",
                xml_escape(&one_line(&m.comment))
            ));
        }
        let fill: Vec<String> = m
            .args
            .iter()
            .map(|a| {
                let var = lower_first(&pascal(&a.name));
                let value = if a.ty.is_int() {
                    format!("{var}.ToString(System.Globalization.CultureInfo.CurrentCulture)")
                } else {
                    var
                };
                format!("(\"{}\", {value})", a.name)
            })
            .collect();
        match &entry.body {
            Body::Plain(_) if m.args.is_empty() => out
                .push_str(&format!("    public static string {name} => Get(\"{name}\");\n\n")),
            Body::Plain(_) => out.push_str(&format!(
                "    public static string {name}({}) => Fill(Get(\"{name}\"), {});\n\n",
                signature(&m.args),
                fill.join(", ")
            )),
            Body::Plural { selector, .. } => {
                let sel = lower_first(&pascal(selector));
                out.push_str(&format!("    public static string {name}({}) => Fill(GetPlural(\"{name}\", {sel}), {});\n\n", signature(&m.args), fill.join(", ")));
            }
        }
    }
    out.push_str("    /// <summary>The languages this build has text for, source first. Draft ones carry the draft label.</summary>\n");
    out.push_str("    public static readonly IReadOnlyList<(string Tag, string Name, string? Flag, bool Draft)> Languages = new (string, string, string?, bool)[]\n    {\n");
    for l in langs {
        out.push_str(&format!(
            "        (\"{}\", \"{}\", {}, {}),\n",
            l.tag,
            c_escape(&l.name),
            l.flag.as_ref().map_or("null".to_owned(), |f| format!("\"{f}\"")),
            if l.draft { "true" } else { "false" }
        ));
    }
    out.push_str("    };\n\n");

    out.push_str("    static readonly Dictionary<string, string> English = new()\n    {\n");
    for entry in &langs[0].entries {
        for (key, value) in keys(&pascal(&entry.source.id), &entry.body) {
            out.push_str(&format!("        [\"{key}\"] = \"{}\",\n", c_escape(&value)));
        }
    }
    out.push_str("    };\n\n");

    out.push_str("    /// <summary>The plural category of a whole number in a language, from CLDR.</summary>\n    public static string Category(string language, long n)\n    {\n        n = Math.Abs(n);\n        var tag = language.Split('-', '_')[0].ToLowerInvariant();\n        switch (tag)\n        {\n");
    let mut seen = std::collections::BTreeSet::new();
    for l in langs {
        let tag = l.tag.split('-').next().unwrap_or(&l.tag);
        if tag == "en" || !seen.insert(tag.to_owned()) {
            continue;
        }
        let table = Table::of(tag)?;
        out.push_str(&format!(
            "            case \"{tag}\":\n                return {};\n",
            pick(&table)
        ));
    }
    let en = Table::of("en")?;
    out.push_str(&format!(
        "            default:\n                return {};\n        }}\n    }}\n\n",
        pick(&en)
    ));

    out.push_str(
        r#"    static string Pick(long n, string small, string tail, char million)
    {
        var letter = n < small.Length ? small[(int)n] : n % 1000000 == 0 ? million : tail[(int)(n % 100)];
        return letter switch { 'z' => "zero", 'o' => "one", 't' => "two", 'f' => "few", 'm' => "many", _ => "other" };
    }

    static string Get(string key)
    {
        var found = Resolver?.Invoke(key);
        if (!string.IsNullOrEmpty(found)) return found;
        return English.TryGetValue(key, out var english) ? english : key;
    }

    static string GetPlural(string key, long n)
    {
        var found = Resolver?.Invoke($"{key}_{Category(Language, n)}");
        if (!string.IsNullOrEmpty(found)) return found;
        // This language has no text for the message: the English one, in the English form.
        return English.TryGetValue($"{key}_{Category("en", n)}", out var english) ? english : key;
    }

    /// <summary>Fills {name} placeholders; a doubled brace is a literal one.</summary>
    static string Fill(string template, params (string Name, string Value)[] values)
    {
        var text = new System.Text.StringBuilder(template.Length + 16);
        for (var i = 0; i < template.Length; i++)
        {
            var c = template[i];
            if ((c == '{' || c == '}') && i + 1 < template.Length && template[i + 1] == c)
            {
                text.Append(c);
                i++;
            }
            else if (c == '{')
            {
                var end = template.IndexOf('}', i);
                if (end < 0) { text.Append(c); continue; }
                var name = template.Substring(i + 1, end - i - 1);
                var hit = Array.FindIndex(values, v => v.Name == name);
                text.Append(hit >= 0 ? values[hit].Value : template.Substring(i, end - i + 1));
                i = end;
            }
            else
            {
                text.Append(c);
            }
        }
        return text.ToString();
    }
}
"#,
    );
    Ok(out)
}

/// C# that returns the category of `n` from a table: a letter per number (z, o, t, f, m, x for
/// zero, one, two, few, many, other), 200 of them, then 100 for the numbers after, and the letter
/// for exact millions.
fn pick(t: &Table) -> String {
    let letters = |cats: &[&str]| -> String { cats.iter().map(|c| letter(c)).collect() };
    format!(
        "Pick(n, \"{}\", \"{}\", '{}')",
        letters(&t.small),
        letters(&t.tail),
        letter(t.million)
    )
}

fn letter(category: &str) -> char {
    match category {
        "zero" => 'z',
        "one" => 'o',
        "two" => 't',
        "few" => 'f',
        "many" => 'm',
        _ => 'x',
    }
}

/// `Msg.Text()` and `Cause.Text()`: each engine message through its own `T` member, so the
/// engine's words are in the person's language. The bindings name a record's fields in Pascal
/// case, and a field named as its own record gets `Value` after it (`Content.ContentValue`).
fn msg_text(cat: &Catalogue) -> String {
    let mut out = String::from(
        "// <auto-generated>\n// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n// </auto-generated>\n#nullable enable\n\nusing Anistream.Engine.Model;\n\nnamespace Anistream.App;\n\n/// <summary>The engine's messages in the person's language. Text anistream does not own is shown as it came.</summary>\npublic static class MsgText\n{\n",
    );
    let mut msgs = String::new();
    let mut causes = String::new();
    for m in cat.source().messages.iter().filter(|m| crate::msg::is_engine(&m.group)) {
        let is_cause = m.id.starts_with("cause-");
        let variant = pascal(m.id.strip_prefix("cause-").unwrap_or(&m.id));
        let parent = if is_cause { "Cause" } else { "Msg" };
        let member = pascal(&m.id);
        let line = if m.args.is_empty() {
            format!("        {parent}.{variant} => T.{member},\n")
        } else {
            let passed: Vec<String> = m
                .args
                .iter()
                .map(|a| {
                    let mut field = pascal(&a.name);
                    if field == variant {
                        field.push_str("Value");
                    }
                    let v = format!("x.{field}");
                    match a.ty {
                        ArgType::Int => v,
                        ArgType::Text => v,
                        ArgType::Cause => format!("{v}.Text()"),
                        ArgType::Seconds => format!("Wording.Span({v})"),
                        ArgType::Bytes => format!("Wording.Size({v})"),
                        ArgType::Percent => format!("Wording.Percent({v})"),
                        ArgType::Timestamp => format!("Wording.Date({v})"),
                        ArgType::Decimal => format!("Wording.Number({v})"),
                    }
                })
                .collect();
            format!("        {parent}.{variant} x => T.{member}({}),\n", passed.join(", "))
        };
        if is_cause { causes.push_str(&line) } else { msgs.push_str(&line) }
    }
    for (name, arms) in [("Msg", msgs), ("Cause", causes)] {
        out.push_str(&format!(
            "    public static string Text(this {name} message) => message switch\n    {{\n"
        ));
        out.push_str(&arms);
        out.push_str(&format!("        {name}.Verbatim x => x.Text,\n"));
        // The bindings and this file come from the same catalogue, so this is never reached.
        out.push_str("        _ => message.ToString() ?? \"\",\n    };\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push_str("\n}\n");
    out
}
