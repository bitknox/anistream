//! Apple: a String Catalog (`Localizable.xcstrings`) and `L.swift`, one typed function per message.
//!
//! Only messages that are shipped are written (see ship.rs): a string marked `needs_review` in the
//! catalogue would be compiled into the app by Xcode, so none is ever emitted.

use anyhow::Result;
use serde_json::{Map, Value, json};

use crate::catalogue::{Arg, ArgType, Body, Catalogue, Part, Platform};
use crate::ship::{Mode, Shipped, select};
use crate::util::{Files, c_escape, camel, one_line, xcode_json};

const DIR: &str = "apple/Packages/AnistreamStrings/Sources/AnistreamStrings";
/// Where the engine's `Msg` is rendered: the store, which sees both the bindings and `L`.
const MSG_PATH: &str =
    "apple/Packages/AnistreamStore/Sources/AnistreamStore/Generated/MsgText.swift";

pub fn generate(cat: &Catalogue, mode: Mode) -> Result<Files> {
    let langs = select(cat, mode, |only| only.is_none() || only == Some(Platform::Apple))?;
    let mut files = Files::new();
    files.insert(format!("{DIR}/Localizable.xcstrings"), xcstrings(cat, &langs));
    files.insert(format!("{DIR}/L.swift"), swift(&langs));
    files.insert(MSG_PATH.to_owned(), msg_text(cat));
    Ok(files)
}

/// A format string with positional specifiers, so word order can change per language.
fn format(parts: &[Part], args: &[Arg]) -> String {
    let has_args = !args.is_empty();
    let mut out = String::new();
    for part in parts {
        match part {
            Part::Text(t) => {
                out.push_str(&if has_args { t.replace('%', "%%") } else { t.clone() })
            }
            Part::Var(v) => {
                let n = args.iter().position(|a| &a.name == v).map_or(1, |i| i + 1);
                out.push_str(&specifier(n, args.get(n - 1).map(|a| a.ty)));
            }
            Part::Term { .. } => unreachable!("terms are inlined before generation"),
        }
    }
    out
}

fn specifier(n: usize, ty: Option<ArgType>) -> String {
    match ty {
        Some(ArgType::Int) => format!("%{n}$lld"),
        _ => format!("%{n}$@"),
    }
}

fn unit(value: String) -> Value {
    json!({ "stringUnit": { "state": "translated", "value": value } })
}

fn localization(body: &Body, args: &[Arg]) -> Value {
    match body {
        Body::Plain(parts) => unit(format(parts, args)),
        // A plural is a substitution on the argument that picks the form: the string is just the
        // placeholder, and each form is a whole sentence, so a language can order its words as it
        // likes. (A plain `variations.plural` would pick the form by the first argument.)
        Body::Plural { selector, variants } => {
            let mut forms = Map::new();
            for v in variants {
                forms.insert(v.category.clone(), unit(format(&v.parts, args)));
            }
            let arg_num = args.iter().position(|a| &a.name == selector).map_or(1, |i| i + 1);
            json!({
                "stringUnit": { "state": "translated", "value": format!("%#@{selector}@") },
                "substitutions": {
                    selector: { "argNum": arg_num, "formatSpecifier": "lld", "variations": { "plural": forms } }
                }
            })
        }
    }
}

fn xcstrings(cat: &Catalogue, langs: &[Shipped]) -> String {
    let mut strings = Map::new();
    for entry in &langs[0].entries {
        let m = &entry.source;
        let mut note = m.comment.clone();
        for (i, a) in m.args.iter().enumerate() {
            note.push_str(&format!(" Argument {}: {} ({:?}).", i + 1, a.name, a.ty));
        }
        let mut locs = Map::new();
        for lang in langs {
            if let Some(e) = lang.entries.iter().find(|e| e.source.id == m.id) {
                locs.insert(lang.tag.clone(), localization(&e.body, &m.args));
            }
        }
        strings.insert(
            m.id.clone(),
            json!({ "comment": note.trim(), "extractionState": "manual", "localizations": locs }),
        );
    }
    xcode_json(
        &json!({ "sourceLanguage": cat.config.source, "strings": strings, "version": "1.0" }),
    )
}

const KEYWORDS: [&str; 6] = ["default", "in", "is", "as", "for", "operator"];

fn label(name: &str) -> String {
    let c = camel(name);
    if KEYWORDS.contains(&c.as_str()) { format!("`{c}`") } else { c }
}

fn swift(langs: &[Shipped]) -> String {
    let mut out = String::from(
        "// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n\nimport Foundation\n\n",
    );
    out.push_str("/// Every string the apps show, by catalogue id. A missing translation falls back to English per string.\n");
    out.push_str("public enum L {\n");
    for entry in &langs[0].entries {
        let m = &entry.source;
        let english = match &entry.body {
            Body::Plain(p) => format(p, &m.args),
            Body::Plural { variants, .. } => {
                let other =
                    variants.iter().find(|v| v.category == "other").unwrap_or(&variants[0]);
                format(&other.parts, &m.args)
            }
        };
        let name = camel(&m.id);
        if !m.comment.is_empty() {
            out.push_str(&format!("    /// {}\n", one_line(&m.comment)));
        }
        if m.args.is_empty() {
            out.push_str(&format!("    public static var {name}: String {{ string(\"{}\", fallback: \"{}\") }}\n\n", m.id, c_escape(&english)));
        } else {
            let params: Vec<String> = m
                .args
                .iter()
                .map(|a| {
                    format!(
                        "{}: {}",
                        label(&a.name),
                        if a.ty.is_int() { "Int" } else { "String" }
                    )
                })
                .collect();
            let names: Vec<String> = m
                .args
                .iter()
                .map(|a| a.name.clone())
                .map(|n| camel(&n))
                .map(|n| if KEYWORDS.contains(&n.as_str()) { format!("`{n}`") } else { n })
                .collect();
            out.push_str(&format!(
                "    public static func {name}({}) -> String {{\n        Self.format(\"{}\", fallback: \"{}\", {})\n    }}\n\n",
                params.join(", "),
                m.id,
                c_escape(&english),
                names.join(", ")
            ));
        }
    }
    out.push_str("    /// The languages this build has text for, source first. `draft` languages carry the draft label.\n");
    out.push_str("    public static let languages: [Language] = [\n");
    for l in langs {
        out.push_str(&format!(
            "        Language(tag: \"{}\", name: \"{}\", flag: {}, draft: {}),\n",
            l.tag,
            c_escape(&l.name),
            l.flag.as_ref().map_or("nil".to_owned(), |f| format!("\"{f}\"")),
            l.draft
        ));
    }
    out.push_str("    ]\n\n");
    out.push_str(
        r#"    public struct Language: Sendable, Equatable {
        public let tag: String
        /// The language's name in itself.
        public let name: String
        /// The ISO code of the flag shown beside the name, if the language has one.
        public let flag: String?
        public let draft: Bool
    }

    /// The bundled flag image of an ISO code (`flag-gb.png`), drawn 4:3.
    public static func flagURL(_ code: String) -> URL? {
        bundle.url(forResource: "flag-\(code)", withExtension: "png")
    }

    private final class BundleToken {}

    private static var bundle: Bundle {
        #if SWIFT_PACKAGE
        Bundle.module
        #else
        Bundle(for: BundleToken.self)
        #endif
    }

    private static func string(_ key: String, fallback: String) -> String {
        bundle.localizedString(forKey: key, value: fallback, table: "Localizable")
    }

    private static func format(_ key: String, fallback: String, _ arguments: CVarArg...) -> String {
        String(format: string(key, fallback: fallback), locale: Locale.current, arguments: arguments)
    }
}
"#,
    );
    out
}

/// `Msg.text` and `Cause.text`: each engine message through its own `L` function, so the engine's
/// words are in the person's language and a new message without a rendering fails to compile.
fn msg_text(cat: &Catalogue) -> String {
    let mut out = String::from(
        "// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n\nimport AnistreamKit\nimport AnistreamStrings\nimport Foundation\n\n",
    );
    let mut msgs = String::new();
    let mut causes = String::new();
    for m in cat.source().messages.iter().filter(|m| crate::msg::is_engine(&m.group)) {
        let is_cause = m.id.starts_with("cause-");
        let case = camel(m.id.strip_prefix("cause-").unwrap_or(&m.id));
        let case = if KEYWORDS.contains(&case.as_str()) { format!("`{case}`") } else { case };
        let l = camel(&m.id);
        let (pattern, call) = if m.args.is_empty() {
            (format!(".{case}"), format!("L.{l}"))
        } else {
            let binds: Vec<String> = m
                .args
                .iter()
                .map(|a| {
                    let n = camel(&a.name);
                    if KEYWORDS.contains(&n.as_str()) { format!("`{n}`") } else { n }
                })
                .collect();
            let lets = binds.iter().map(|b| format!("let {b}")).collect::<Vec<_>>().join(", ");
            let passed: Vec<String> = m
                .args
                .iter()
                .zip(&binds)
                .map(|(a, b)| {
                    let value = match a.ty {
                        ArgType::Int | ArgType::Timestamp => format!("Int({b})"),
                        ArgType::Cause => format!("{b}.text"),
                        ArgType::Seconds => format!("spanText({b})"),
                        ArgType::Bytes => format!("sizeText({b})"),
                        _ => b.clone(),
                    };
                    format!("{}: {value}", label(&a.name))
                })
                .collect();
            (format!(".{case}({lets})"), format!("L.{l}({})", passed.join(", ")))
        };
        let line = format!("        case {pattern}: {call}\n");
        if is_cause { causes.push_str(&line) } else { msgs.push_str(&line) }
    }
    out.push_str("extension Msg {\n    /// The message in the person's language. Text anistream does not own is shown as it came.\n    public var text: String {\n        switch self {\n");
    out.push_str(&msgs);
    out.push_str("        case let .verbatim(text): text\n        }\n    }\n}\n\n");
    out.push_str("extension Cause {\n    public var text: String {\n        switch self {\n");
    out.push_str(&causes);
    out.push_str("        case let .verbatim(text): text\n        }\n    }\n}\n\n");
    out.push_str(r#"private func spanText(_ s: AnistreamKit.Span) -> String {
    let days = Int(s.days), hours = Int(s.hours), minutes = Int(s.minutes), seconds = Int(s.seconds)
    if days > 0 {
        return hours > 0 ? L.durationDaysHours(days: days, hours: hours) : L.durationDays(days: days)
    }
    if hours > 0 {
        return minutes > 0 ? L.durationHoursMinutes(hours: hours, minutes: minutes) : L.durationHours(hours: hours)
    }
    if minutes > 0 {
        return seconds > 0
            ? L.durationMinutesSeconds(minutes: minutes, seconds: String(format: "%02d", seconds))
            : L.durationMinutes(minutes: minutes)
    }
    return seconds > 0 ? L.durationSeconds(seconds: seconds) : L.durationMinutes(minutes: 0)
}

private func sizeText(_ s: Size) -> String {
    let number = s.value.formatted(.number.precision(.fractionLength(Int(s.decimals))))
    switch s.unit {
    case .byte: return L.sizeByte(value: number)
    case .kilobyte: return L.sizeKilobyte(value: number)
    case .megabyte: return L.sizeMegabyte(value: number)
    case .gigabyte: return L.sizeGigabyte(value: number)
    }
}
"#);
    out
}
