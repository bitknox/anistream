//! Rust, for the terminal, the Linux app and (later) the engine: Fluent loaded at runtime by
//! `anistream-i18n`. The shipped messages of each language are written back as Fluent, with terms
//! written out, so the runtime parses exactly what the other targets are given; `locales.rs`
//! embeds them and `t.rs` has one typed function per message.

use anyhow::Result;

use crate::catalogue::{Arg, Body, Catalogue, Part, Platform};
use crate::pseudo;
use crate::ship::{Mode, Shipped, ShippedEntry, select};
use crate::util::{Files, one_line, rust_escape, snake};

const CRATE: &str = "crates/anistream-i18n";
pub const PSEUDO_TAG: &str = "en-XA";

pub fn generate(cat: &Catalogue, mode: Mode) -> Result<Files> {
    let langs = select(cat, mode, |only| {
        only.is_none() || matches!(only, Some(Platform::Linux | Platform::Tui))
    })?;
    let mut files = Files::new();
    for lang in &langs {
        files
            .insert(format!("{CRATE}/ftl/{}.ftl", lang.tag), ftl(&lang.entries, |b| b.clone()));
    }
    // The pseudo-locale is made from the source language and never shipped in a release build.
    files.insert(format!("{CRATE}/ftl/{PSEUDO_TAG}.ftl"), ftl(&langs[0].entries, pseudo::body));
    files.insert(format!("{CRATE}/src/locales.rs"), locales(&langs));
    files.insert(format!("{CRATE}/src/t.rs"), t(&langs[0]));
    Ok(files)
}

fn pattern(parts: &[Part]) -> String {
    let mut out = String::new();
    for part in parts {
        match part {
            Part::Text(t) => {
                for c in t.chars() {
                    match c {
                        '{' => out.push_str("{ \"{\" }"),
                        '}' => out.push_str("{ \"}\" }"),
                        '\n' => out.push_str("\n    "),
                        c => out.push(c),
                    }
                }
            }
            Part::Var(v) => out.push_str(&format!("{{ ${v} }}")),
            Part::Term { .. } => unreachable!("terms are inlined before generation"),
        }
    }
    out
}

fn ftl(entries: &[ShippedEntry], map: impl Fn(&Body) -> Body) -> String {
    let mut out = String::from("# Generated by tools/i18n from i18n/. Do not edit.\n\n");
    for e in entries {
        let m = &e.source;
        if !m.comment.is_empty() {
            out.push_str(&format!("# {}\n", one_line(&m.comment)));
        }
        match map(&e.body) {
            Body::Plain(parts) => out.push_str(&format!("{} = {}\n", m.id, pattern(&parts))),
            Body::Plural { selector, variants } => {
                out.push_str(&format!("{} =\n    {{ ${selector} ->\n", m.id));
                for v in &variants {
                    let star = if v.category == "other" { "*" } else { " " };
                    out.push_str(&format!(
                        "       {star}[{}] {}\n",
                        v.category,
                        pattern(&v.parts)
                    ));
                }
                out.push_str("    }\n");
            }
        }
        out.push('\n');
    }
    out
}

fn locales(langs: &[Shipped]) -> String {
    let mut out = String::from(
        "// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n\nuse crate::Locale;\n\n/// The language the catalogue is written in, and the one every missing string falls back to.\npub const SOURCE: &str = \"",
    );
    out.push_str(&langs[0].tag);
    out.push_str("\";\n\n/// The languages this build has text for, source first.\npub const LOCALES: &[Locale] = &[\n");
    for l in langs {
        out.push_str(&format!(
            "    Locale {{ tag: \"{}\", name: \"{}\", flag: {}, draft: {}, ftl: include_str!(\"../ftl/{}.ftl\") }},\n",
            l.tag,
            rust_escape(&l.name),
            l.flag.as_ref().map_or("None".to_owned(), |f| format!("Some(\"{f}\")")),
            l.draft,
            l.tag
        ));
    }
    out.push_str("];\n\n");
    out.push_str(&format!(
        "/// Accented, padded English for looking at layouts. Never in a release build unless `pseudo` is on.\n#[cfg(any(debug_assertions, feature = \"pseudo\"))]\npub const PSEUDO: Locale = Locale {{ tag: \"{PSEUDO_TAG}\", name: \"English (pseudo)\", flag: None, draft: true, ftl: include_str!(\"../ftl/{PSEUDO_TAG}.ftl\") }};\n"
    ));
    out
}

fn rust_args(args: &[Arg]) -> (String, String) {
    let params: Vec<String> = args
        .iter()
        .map(|a| format!("{}: {}", snake(&a.name), if a.ty.is_int() { "i64" } else { "&str" }))
        .collect();
    let pass: Vec<String> = args
        .iter()
        .map(|a| {
            format!(
                "(\"{}\", {}({}))",
                a.name,
                if a.ty.is_int() { "Arg::Int" } else { "Arg::Text" },
                snake(&a.name)
            )
        })
        .collect();
    (params.join(", "), pass.join(", "))
}

fn t(source: &Shipped) -> String {
    let mut out = String::from(
        "// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\n\n//! One function per message, in the language set with `set_language`.\n\nuse crate::{Arg, text};\n\n",
    );
    for e in &source.entries {
        let m = &e.source;
        if !m.comment.is_empty() {
            out.push_str(&format!("/// {}\n", one_line(&m.comment)));
        }
        let (params, pass) = rust_args(&m.args);
        out.push_str(&format!(
            "pub fn {}({params}) -> String {{\n    text(\"{}\", &[{pass}])\n}}\n\n",
            snake(&m.id),
            m.id
        ));
    }
    out
}
