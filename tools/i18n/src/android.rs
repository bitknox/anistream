//! Android: `strings.xml` with `<plurals>` per language in the `:i18n` module, the locale list the
//! system's per-app language setting reads, and `Strings.kt` for code that has no composition.
//! Names are snake_case, so `R.string.x` and `R.plurals.x` fail to compile when a key is gone.

use anyhow::Result;

use crate::catalogue::{Arg, ArgType, Body, Catalogue, Part, Platform};
use crate::ship::{Mode, Shipped, select};
use crate::util::{Files, c_escape, camel, one_line, snake, xml_escape};

const MODULE: &str = "android/i18n/src/main";

pub fn generate(cat: &Catalogue, mode: Mode) -> Result<Files> {
    let langs = select(cat, mode, |only| only.is_none() || only == Some(Platform::Android))?;
    let mut files = Files::new();
    for lang in &langs {
        files.insert(
            format!("{MODULE}/res/{}/strings.xml", values_dir(&lang.tag, lang.is_source)),
            strings_xml(lang),
        );
    }
    files.insert(format!("{MODULE}/res/xml/locales_config.xml"), locales_config(&langs));
    files.insert(format!("{MODULE}/kotlin/tv/anistream/i18n/Strings.kt"), kotlin(&langs));
    Ok(files)
}

/// `da` is `values-da`; a tag with a region is the BCP 47 form `values-b+pt+BR`.
pub fn values_dir(tag: &str, is_source: bool) -> String {
    if is_source {
        "values".to_owned()
    } else if tag.contains('-') {
        format!("values-b+{}", tag.replace('-', "+"))
    } else {
        format!("values-{tag}")
    }
}

fn escape(text: &str, has_args: bool, at_start: bool) -> String {
    let mut out = String::new();
    for (i, c) in text.chars().enumerate() {
        match c {
            '\'' => out.push_str("\\'"),
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '@' | '?' if i == 0 && at_start => {
                out.push('\\');
                out.push(c);
            }
            '%' if has_args => out.push_str("%%"),
            c => out.push_str(&xml_escape(&c.to_string())),
        }
    }
    out
}

fn text(parts: &[Part], args: &[Arg]) -> String {
    let mut out = String::new();
    // Literal text is escaped as a whole, so a leading `@` is seen at the start of the string.
    let mut literal = String::new();
    let mut first = true;
    let flush = |literal: &mut String, out: &mut String, first: &mut bool| {
        if !literal.is_empty() {
            out.push_str(&escape(literal, !args.is_empty(), *first));
            literal.clear();
        }
        *first = false;
    };
    for part in parts {
        match part {
            Part::Text(t) => literal.push_str(t),
            Part::Var(v) => {
                flush(&mut literal, &mut out, &mut first);
                let n = args.iter().position(|a| &a.name == v).map_or(1, |i| i + 1);
                out.push_str(&match args.get(n - 1).map(|a| a.ty) {
                    Some(ArgType::Int) => format!("%{n}$d"),
                    _ => format!("%{n}$s"),
                });
            }
            Part::Term { .. } => unreachable!("terms are inlined before generation"),
        }
    }
    flush(&mut literal, &mut out, &mut first);
    out
}

fn strings_xml(lang: &Shipped) -> String {
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n     `cargo run -p i18n-tool -- generate`. -->\n<resources>\n",
    );
    for entry in &lang.entries {
        let m = &entry.source;
        let name = snake(&m.id);
        if lang.is_source && !m.comment.is_empty() {
            out.push_str(&format!(
                "    <!-- {} -->\n",
                one_line(&m.comment).replace("--", "- -")
            ));
        }
        match &entry.body {
            Body::Plain(parts) => out.push_str(&format!(
                "    <string name=\"{name}\">{}</string>\n",
                text(parts, &m.args)
            )),
            Body::Plural { variants, .. } => {
                out.push_str(&format!("    <plurals name=\"{name}\">\n"));
                for v in variants {
                    out.push_str(&format!(
                        "        <item quantity=\"{}\">{}</item>\n",
                        v.category,
                        text(&v.parts, &m.args)
                    ));
                }
                out.push_str("    </plurals>\n");
            }
        }
    }
    out.push_str("</resources>\n");
    out
}

fn locales_config(langs: &[Shipped]) -> String {
    let mut out = String::from(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/i18n from i18n/languages.toml. Do not edit. -->\n<locale-config xmlns:android=\"http://schemas.android.com/apk/res/android\">\n",
    );
    for l in langs {
        out.push_str(&format!("    <locale android:name=\"{}\" />\n", l.tag));
    }
    out.push_str("</locale-config>\n");
    out
}

fn kotlin(langs: &[Shipped]) -> String {
    let mut out = String::from(
        "// Generated by tools/i18n from i18n/. Do not edit: change the catalogue and run\n// `cargo run -p i18n-tool -- generate`.\npackage tv.anistream.i18n\n\nimport android.content.Context\n\n",
    );
    out.push_str("/**\n * Strings for code that has no composition (notifications, widgets, services). Screens call\n * `stringResource(R.string.x)` and `pluralStringResource(R.plurals.x, n, ...)` directly.\n */\nobject Strings {\n");
    for entry in &langs[0].entries {
        let m = &entry.source;
        let name = camel(&m.id);
        let res = snake(&m.id);
        if !m.comment.is_empty() {
            out.push_str(&format!(
                "    /** {} */\n",
                one_line(&m.comment).replace("*/", "* /")
            ));
        }
        let mut params = vec!["context: Context".to_owned()];
        params.extend(m.args.iter().map(|a| {
            format!("{}: {}", camel(&a.name), if a.ty.is_int() { "Int" } else { "String" })
        }));
        let call_args: Vec<String> = m.args.iter().map(|a| camel(&a.name)).collect();
        let body = match entry.body {
            Body::Plain(_) if call_args.is_empty() => {
                format!("context.getString(R.string.{res})")
            }
            Body::Plain(_) => {
                format!("context.getString(R.string.{res}, {})", call_args.join(", "))
            }
            Body::Plural { ref selector, .. } => format!(
                "context.resources.getQuantityString(R.plurals.{res}, {}, {})",
                camel(selector),
                call_args.join(", ")
            ),
        };
        out.push_str(&format!(
            "    fun {name}({}): String =\n        {body}\n\n",
            params.join(", ")
        ));
    }
    out.push_str("    /** The languages this build has text for, source first. Draft ones carry the draft label. */\n");
    out.push_str("    val languages: List<Language> = listOf(\n");
    for l in langs {
        out.push_str(&format!(
            "        Language(\"{}\", \"{}\", {}),\n",
            l.tag,
            c_escape(&l.name),
            l.draft
        ));
    }
    out.push_str("    )\n}\n\n/** A language the build has text for; [name] is the language's name in itself. */\ndata class Language(val tag: String, val name: String, val draft: Boolean)\n");
    out
}
